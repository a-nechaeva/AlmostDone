"""Interfaces used by application services, independent of concrete adapters."""
from contextlib import AbstractContextManager
from typing import Any, Protocol


class AuthProvider(Protocol):
    def exchange(self, payload: dict) -> str: ...


class Recognizer(Protocol):
    def recognize(self, image: bytes, kind: str) -> list[dict]: ...


class RecognitionFailure(Exception):
    """Recognition completed but the image could not be understood."""


class CatalogRepository(Protocol):
    def load(self) -> dict: ...


class EngineGateway(Protocol):
    unsupported_recipes: set[str]

    def configure(self, data: dict) -> None: ...
    def require_engine(self) -> None: ...
    def search(self, query: str) -> list[str]: ...
    def detail(self, recipe_id, stock, banned): ...
    def reachable(self, stock, banned, arguments): ...
    def shopping_requirement(self, code, grams): ...
    def build_graph(self, options): ...
    def single_purchases(self, options): ...


class RuntimeRecords(Protocol):
    def get(self, data, collection, key): ...
    def put(self, data, collection, key, value) -> None: ...
    def delete(self, data, collection, key) -> None: ...
    def items(self, data, collection) -> list: ...


class Repository(Protocol):
    mode: str
    persistent: bool
    runtime: RuntimeRecords

    def transaction(self) -> AbstractContextManager[Any]: ...
    def user(self, db, user_id: str) -> dict | None: ...
    def save(self, db, user_id: str, state: dict) -> None: ...
    def identity(self, db, login: str, password_marker: str) -> dict: ...
