"""Промпты для LLM.

Чек (receipt) — один запрос: модель читает строки чека и сразу сопоставляет их со списком
ингредиентов каталога (название — синонимы — код). Текст на чеке не даёт ей выдумывать продукты.

Фото продуктов (products) — два запроса:
  1. картинка БЕЗ каталога: модель перечисляет то, что видит. Если показать ей список каталога,
     на фото без текста она начинает «узнавать» продукты из списка, которых на фото нет;
  2. текст без картинки: найденные названия сопоставляются с каталогом. Здесь выдумать новый
     продукт нельзя — модель только сопоставляет то, что получила.
"""

from __future__ import annotations

from collections.abc import Sequence

from ..models import Catalog
from .models import RecognitionKind

MATCH_RULES = """\
- code — только из каталога. Сопоставляй по русскому названию продукта, а не по коду:
  код — технический идентификатор на английском.
- Выбирай продукт из каталога, только если это тот же продукт. Похожий продукт — не тот же:
  колбаса — не сосиски, сельдь — не куриное филе, болгарский перец — не чёрный молотый перец,
  салат — не сахар, повидло — не яблоки. Если такого продукта в каталоге нет, candidates = [].
- Другой сорт того же продукта (ржаной хлеб вместо пшеничного, томаты черри вместо помидоров)
  допустим, но с confidence не выше 0.7.
- В candidates от 0 до 3 вариантов, самый вероятный первым. confidence — уверенность от 0 до 1;
  1.0 — только если сомнений нет совсем."""

QUANTITY_RULES = """\
- quantity указывай, только если оно прямо видно: вес, объём или число штук. Килограммы переводи
  в граммы, литры — в миллилитры. Если количество не видно — null. Ничего не придумывай."""

RECEIPT_PROMPT = """\
Это фото или скриншот кассового чека из продуктового магазина.
- Перебери все товарные строки чека. raw_name — строка товара как на чеке, без цены, по-русски.
- Пропускай всё, что не является едой: пакеты, посуду, журналы, скидки, бонусы, итоги, НДС, кассира.
- Названия на чеках сокращены («МОЛ.ПАСТ.2,5% 1Л», «ЯЙЦО С1 10ШТ») — сопоставь их с каталогом.
- Количество бери из строки: вес («0,532 кг» → 532 g), штуки («10ШТ» → 10 pcs),
  объём или вес упаковки в названии («1Л» → 1000 ml, «200Г» → 200 g).
{match_rules}
{quantity_rules}
- Каждая строка чека — отдельный элемент items. Если еды в чеке нет — {{"items": []}}.

Ответь ТОЛЬКО JSON-объектом, без пояснений и без markdown:
{{"items": [
  {{"raw_name": "<строка товара>",
   "candidates": [{{"code": "<код из каталога>", "confidence": <0..1>}}],
   "quantity": {{"value": <число>, "unit": "g" | "ml" | "pcs"}} или null}}
]}}

Каталог (название → код):
{catalog}"""

PRODUCTS_PROMPT = """\
Это фото продуктов: холодильник, полка, стол или пакет с покупками.
Перечисли продукты, которые действительно видны на фото. Не добавляй ничего, чего не видно,
даже если такие продукты обычно лежат в холодильнике.
- name — русское название продукта, как назвал бы его человек: «творог», «куриные яйца»,
  «шампиньоны», «ветчина». Если на упаковке читается название — бери его смысл, а не бренд.
  Если на упаковке написано по-английски — всё равно пиши по-русски.
- Не угадывай содержимое непрозрачных контейнеров, банок без этикетки, бутылок и пакетов.
- confidence — уверенность от 0 до 1, что на фото именно этот продукт. Если сомневаешься — ниже 0.5.
- count — сколько одинаковых упаковок или штук видно, если можно уверенно посчитать; иначе null.
- quantity — вес или объём одной упаковки, только если он читается на упаковке; иначе null.
- Одинаковые упаковки — один элемент с count, а не несколько одинаковых элементов.

Ответь ТОЛЬКО JSON-объектом, без пояснений и без markdown:
{"items": [
  {"name": "<русское название>", "confidence": <0..1>, "count": <число> или null,
   "quantity": {"value": <число>, "unit": "g" | "ml" | "pcs"} или null}
]}
Если еды на фото не видно — {"items": []}."""

MAPPING_PROMPT = """\
Сопоставь каждый продукт из списка «Найдено» с каталогом.
{match_rules}
- Для каждого номера из списка «Найдено» — ровно один элемент matches.

Ответь ТОЛЬКО JSON-объектом, без пояснений и без markdown:
{{"matches": [{{"index": <номер>, "candidates": [{{"code": "<код из каталога>", "confidence": <0..1>}}]}}]}}

Найдено:
{found}

Каталог (название → код):
{catalog}"""


def catalog_listing(catalog: Catalog) -> str:
    """«Название (синонимы) → код»: название первым, чтобы модель сопоставляла по нему, а не по коду."""
    lines = []
    for code, ing in sorted(catalog.ingredients.items(), key=lambda kv: kv[1].name):
        aliases = f" ({', '.join(ing.aliases)})" if ing.aliases else ""
        lines.append(f"{ing.name}{aliases} → {code}")
    return "\n".join(lines)


def build_receipt_prompt(catalog: Catalog) -> str:
    return RECEIPT_PROMPT.format(match_rules=MATCH_RULES, quantity_rules=QUANTITY_RULES, catalog=catalog_listing(catalog))


def build_products_prompt() -> str:
    return PRODUCTS_PROMPT


def build_mapping_prompt(names: Sequence[str], catalog: Catalog) -> str:
    found = "\n".join(f"{i}. {name}" for i, name in enumerate(names, 1))
    return MAPPING_PROMPT.format(match_rules=MATCH_RULES, found=found, catalog=catalog_listing(catalog))


def build_prompt(kind: RecognitionKind, catalog: Catalog) -> str:
    """Промпт запроса с картинкой: для чека — с каталогом, для фото продуктов — без него."""
    return build_receipt_prompt(catalog) if kind == "receipt" else build_products_prompt()
